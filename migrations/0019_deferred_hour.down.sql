-- Reverse 0019. deferred_hour is token-push bookkeeping; dropping it loses
-- which hours are waiting for the manager to accept a kind they list. With the
-- previous release (rollbacks are not supported, rulings.md 2026-10-14; this describes
-- what would happen):
--   * a deferred hour that was never accepted is an unsent hour again: it is
--     re-sent, and that release's run stops at the first such refusal, as it
--     did before 0019;
--   * a deferred hour that the manager accepted earlier with fewer kinds (for
--     instance its token records, before video was rated into it) has a
--     pushed_hour row, so it is NOT an unsent hour: it is re-sent only while
--     it is in the trailing window, and the kind the manager refused (its
--     video) never reaches the manager once the hour leaves the window, unless
--     an operator re-sends it with -since/-until after upgrading.
DROP TABLE IF EXISTS deferred_hour;
